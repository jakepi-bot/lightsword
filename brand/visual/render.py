#!/usr/bin/env python3
"""Render the Lightsword social template set to PNG.

    python3 render.py            # all assets
    python3 render.py T01 T04    # named assets only
    python3 render.py --check    # re-verify existing exports, no render

Copy lives in content.json. Layout lives in templates/*.html.
Both are plain text: edit, re-run, never hand-tune a PNG.
"""
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TEMPLATES = ROOT / "templates"
EXPORTS = ROOT / "exports"
BUILD = ROOT / "build"
MARK = (ROOT / "src" / "mark.html").read_text()
CHROME = shutil.which("chromium") or shutil.which("chromium-browser") or shutil.which("google-chrome")

MARK_SIZES = {"mark": 56, "mark_sm": 40, "mark_lg": 260}


def load():
    return json.loads((ROOT / "content.json").read_text())


def snippet(size: int) -> str:
    return MARK.replace("{{size}}", str(size))


def substitute(html: str, variables: dict) -> str:
    for key, size in MARK_SIZES.items():
        html = html.replace("{{%s}}" % key, snippet(size))
    unresolved = set(re.findall(r"\{\{(\w+)\}\}", html))
    missing = unresolved - set(variables)
    if missing:
        raise SystemExit("missing copy for: %s" % ", ".join(sorted(missing)))
    for key, value in variables.items():
        html = html.replace("{{%s}}" % key, str(value).replace("\n", "<br>"))
    leftover = re.findall(r"\{\{\w+\}\}", html)
    if leftover:
        raise SystemExit("unresolved tokens: %s" % leftover)
    return html


def render(asset, fmt):
    html = substitute((TEMPLATES / fmt["template"]).read_text(), asset["vars"])
    BUILD.mkdir(exist_ok=True)
    page = BUILD / f"{asset['id']}-{fmt['slug']}.html"
    page.write_text(html)

    out = EXPORTS / f"{fmt['slug']}-{fmt['w']}x{fmt['h']}.png"
    EXPORTS.mkdir(exist_ok=True)
    cmd = [
        CHROME, "--headless=new", "--no-sandbox", "--disable-gpu",
        "--hide-scrollbars", "--force-device-scale-factor=1",
        "--disable-lcd-text", "--default-background-color=00000000",
        f"--window-size={fmt['w']},{fmt['h']}",
        "--virtual-time-budget=4000",
        f"--screenshot={out}",
        page.as_uri(),
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
    if proc.returncode != 0 or not out.exists():
        raise SystemExit(f"render failed for {asset['id']}: {proc.stderr[-800:]}")
    return out


def check(assets, formats):
    from PIL import Image
    ok = True
    for asset in assets:
        fmt = formats[asset["id"]]
        path = EXPORTS / f"{fmt['slug']}-{fmt['w']}x{fmt['h']}.png"
        if not path.exists():
            print(f"  MISSING {path.name}")
            ok = False
            continue
        img = Image.open(path).convert("RGB")
        colours = len(img.getcolors(maxcolors=250000) or [])
        size_ok = img.size == (fmt["w"], fmt["h"])
        print(f"  {'OK  ' if size_ok else 'BAD '} {path.name:<44} {img.size[0]}x{img.size[1]}  "
              f"{path.stat().st_size // 1024} KB  colours={colours}")
        if not size_ok or colours < 40:
            ok = False
    return ok


def main(argv):
    data = load()
    assets, formats = data["assets"], data["formats"]
    if argv and argv[0] == "--check":
        return 0 if check(assets, formats) else 1
    if argv:
        wanted = {a.strip().upper() for a in argv}
        assets = [a for a in assets if a["id"] in wanted]
    if not CHROME:
        raise SystemExit("chromium not found on PATH")

    lines = ["# Alt text — Lightsword social assets", "",
             "Paste the matching line into the Bluesky image description field.",
             "Generated by `render.py`; do not edit by hand.", ""]
    for asset in assets:
        fmt = formats[asset["id"]]
        out = render(asset, fmt)
        rel = out.relative_to(ROOT)
        print(f"rendered {rel}")
        lines.append(f"## {rel.name}")
        lines.append("")
        lines.append(asset["alt"])
        lines.append("")
    if len(assets) == len(data["assets"]):
        (EXPORTS / "alt-text.md").write_text("\n".join(lines))
        (ROOT / "manifest.json").write_text(json.dumps({
            "generated_by": "render.py",
            "formats": formats,
            "assets": [{**{k: v for k, v in a.items() if k != "vars"},
                        "file": f"exports/{formats[a['id']]['slug']}-{formats[a['id']]['w']}x{formats[a['id']]['h']}.png"}
                       for a in data["assets"]],
        }, indent=2) + "\n")
    return 0 if check(assets, formats) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
